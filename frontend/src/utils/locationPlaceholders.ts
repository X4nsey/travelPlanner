function cleanString(str?: string | null): string {
  if (!str) return '';
  return str.toLowerCase().trim().replace(/[.,/#!$%^&*;:{}=\-_`~()]/g, ' ').replace(/\s+/g, ' ');
}

/**
 * Возвращает актуальный контекстный placeholder для поля ввода места проведения
 * на основе страны и города поездки.
 */
export function getLocationPlaceholder(country?: string | null, city?: string | null): string {
  const cleanCity = cleanString(city);
  const cleanCountry = cleanString(country);

  // 1. Поиск совпадений по городу (наиболее точный контекст)
  if (cleanCity) {
    for (const item of CITY_LANDMARKS) {
      if (item.aliases.some((alias) => cleanCity === alias || cleanCity.includes(alias) || alias.includes(cleanCity))) {
        return item.placeholder;
      }
    }
  }

  // 1.1 Также проверяем, не указан ли город внутри строки страны (например, "Франция, Париж")
  if (cleanCountry) {
    for (const item of CITY_LANDMARKS) {
      if (item.aliases.some((alias) => cleanCountry.includes(alias))) {
        return item.placeholder;
      }
    }
  }

  // 2. Поиск совпадений по стране
  if (cleanCountry) {
    for (const item of COUNTRY_LANDMARKS) {
      if (item.aliases.some((alias) => cleanCountry === alias || cleanCountry.includes(alias) || alias.includes(cleanCountry))) {
        return item.placeholder;
      }
    }
  }

  // 3. Умный запасной вариант с подстановкой переданного города или страны
  if (city && city.trim()) {
    const trimmedCity = city.trim();
    return `Например: Центральная площадь (${trimmedCity}) / Отель в центре / Аэропорт`;
  }

  if (country && country.trim()) {
    const trimmedCountry = country.trim();
    return `Например: Главная площадь (${trimmedCountry}) / Отель в центре / Аэропорт`;
  }

  // 4. Общий дефолтный placeholder, если направление не указано вовсе
  return 'Например: Центральная площадь / Отель в центре / Аэропорт';
}
